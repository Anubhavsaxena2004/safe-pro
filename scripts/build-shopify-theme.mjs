// Builds Shopify theme files from the paste-in snippets in shopify/, so both ways of
// installing (theme editor "Custom Liquid" or Shopify CLI `theme push`) use the same code.
//   npm run shopify:build   →   shopify/theme/{sections,snippets,templates}
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = (f) => readFileSync(path.join(root, "shopify", f), "utf8").replace(/\r\n/g, "\n");
const out = path.join(root, "shopify", "theme");
const NOTE = "{%- comment -%} Generated by scripts/build-shopify-theme.mjs from shopify/{file}. Edit that file instead. {%- endcomment -%}\n";

// Drop the "HOW TO ADD" comment at the top of each snippet.
const body = (file) => src(file).replace(/^\{%- comment -%\}[\s\S]*?\{%- endcomment -%\}\n*/, "");

function write(rel, content) {
  const file = path.join(out, rel);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log("  wrote", path.relative(root, file));
}

// 1. Booking form as a section, usable only on page templates.
write(
  "sections/kiddough-home-care.liquid",
  NOTE.replace("{file}", "home-care-page.liquid") +
    `<div class="page-width">\n${body("home-care-page.liquid")}</div>\n\n` +
    `{% schema %}\n${JSON.stringify(
      {
        name: "Kiddough Home Care",
        tag: "section",
        class: "section",
        settings: [{ type: "paragraph", content: "Booking form for Kiddough Safe Pro visits. Requests go to the Safe Pro app; nothing is changed in the store." }],
        presets: [{ name: "Kiddough Home Care" }],
        enabled_on: { templates: ["page"] },
      },
      null,
      2,
    )}\n{% endschema %}\n`,
);

// 2. Product buttons as a section for the product template (added in the theme editor).
const buttons = body("product-buttons.liquid");
const pageAssign = "{%- assign kd_page = '/pages/home-care' -%}";
const productAssign = "{%- assign kd_product = kd_product | default: product -%}";
for (const line of [pageAssign, productAssign]) {
  if (!buttons.includes(line)) throw new Error(`product-buttons.liquid: expected line not found: ${line}`);
}
const sectionButtons = buttons
  .replace(pageAssign, "{%- assign kd_page = section.settings.page_url | default: '/pages/home-care' -%}")
  .replace(productAssign, "{%- assign kd_product = product -%}"); // sections on the product template get `product`
write(
  "sections/kiddough-service-buttons.liquid",
  NOTE.replace("{file}", "product-buttons.liquid") +
    `<div class="page-width">\n${sectionButtons}</div>\n\n` +
    `{% schema %}\n${JSON.stringify(
      {
        name: "Kiddough service buttons",
        tag: "section",
        class: "section",
        settings: [{ type: "text", id: "page_url", label: "Booking page URL", default: "/pages/home-care" }],
        presets: [{ name: "Kiddough service buttons" }],
        enabled_on: { templates: ["product"] },
      },
      null,
      2,
    )}\n{% endschema %}\n`,
);

// 3. Same buttons as a snippet, for product cards: {% render 'kiddough-home-care-buttons', kd_product: card_product %}
write("snippets/kiddough-home-care-buttons.liquid", NOTE.replace("{file}", "product-buttons.liquid") + buttons);

// 4. Page template that shows the booking form. Assign it to the "Home Care" page.
write(
  "templates/page.home-care.json",
  JSON.stringify({ sections: { main: { type: "kiddough-home-care", settings: {} } }, order: ["main"] }, null, 2) + "\n",
);
